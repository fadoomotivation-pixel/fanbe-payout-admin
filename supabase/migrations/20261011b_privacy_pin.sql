-- The PIN behind the privacy lock, readable by the super-admin in Supabase.
--
-- Admin: "agar 15 min se system nahi use hua ... broker ne kya kamaya or
-- broker ka number blur ho jae ... ek pin dalne ka option aye to blur hat
-- jae ... normal employee galti se data na chura le laptop se."
--
-- And then: "As a superadmin mujhe bhi supabase me pta chlata rahe ki kya
-- pin h abhi.. agar change kr de koi to".
--
-- WHAT THIS IS, PLAINLY. The blur itself is a style, and a style is not
-- security: anyone who opens the browser's dev tools, or calls the REST API
-- with the anon key, still sees the numbers. What it does stop is the thing
-- that actually happens in an office - a laptop left open, someone walking
-- past, a photo of the broker list and what each one earns. For an affiliate
-- network that list IS the business, so it is worth locking the screen even
-- though it is not worth calling it encryption.
--
-- WHY THE PIN IS STORED AS PLAIN TEXT, AND WHY THAT IS THE RIGHT CALL HERE.
-- A hash cannot be read back - that is the whole point of one - so a hashed
-- PIN could never answer "kya pin h abhi". The question is what the hash
-- would have been protecting. This PIN guards a blur on a screen, nothing
-- more. Every number the blur hides - what each broker earned, every phone
-- number - sits in this same database in plain text. Anyone who can read
-- app_security can already read brokers and payout_distributions directly
-- and does not need the PIN at all. So the hash was buying no safety, while
-- costing the owner of the business sight of his own PIN.
--
-- WHAT STILL PROTECTS IT. The table has RLS on with NO policies and every
-- grant revoked from anon and authenticated, so no employee can read the PIN
-- through the API, logged in or not. Only these SECURITY DEFINER functions,
-- and the Supabase dashboard, can reach it. The browser sends a guess and
-- gets back true or false; the PIN itself never leaves the server.
--
-- One warning that follows from plain text: do not set this to a PIN used
-- anywhere that matters - a bank card, a phone lock. It is an office screen
-- PIN and the owner can read it.
--
-- A four-digit PIN is 10,000 guesses, which a script finishes in seconds, so
-- verify_privacy_pin() throttles: five wrong tries and it refuses everyone
-- for a minute. That turns a seconds-long attack into a days-long one, which
-- is the most a short PIN can honestly give.
--
-- Seeded with 1947 because that is what admin asked for. It is also a date
-- every person in India would guess first, so the app offers "Change PIN".
--
-- "AGAR CHANGE KR DE KOI TO" - every change is written to app_security_log
-- with the time, the login's name and email, and the old and new PIN. So a
-- change can be seen, not just suspected. One query answers both questions:
--
--     select * from public.privacy_pin_status;
--
-- Plain ASCII, short lines, no long rules or box-drawing. A banner of
-- repeated punctuation has already cost us one failed paste on a phone: the
-- leading "--" was dropped in transit and Postgres read the rest as an
-- operator.
--
-- Safe to run more than once. Deletes nothing.

BEGIN;

CREATE TABLE IF NOT EXISTS public.app_security (
  key        text PRIMARY KEY,
  value      text NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.app_security ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_security FROM PUBLIC, anon, authenticated;

-- Who changed the PIN, when, and from what to what.
CREATE TABLE IF NOT EXISTS public.app_security_log (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  changed_at       timestamptz NOT NULL DEFAULT now(),
  changed_by       uuid,
  changed_by_name  text,
  changed_by_email text,
  old_pin          text,
  new_pin          text,
  note             text
);

ALTER TABLE public.app_security_log ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.app_security_log FROM PUBLIC, anon, authenticated;

INSERT INTO public.app_security (key, value)
VALUES ('privacy_pin', '1947')
ON CONFLICT (key) DO NOTHING;

-- If an earlier draft of this file ran and stored a bcrypt hash, swap it for
-- a PIN the owner can actually read, and say so in the log rather than
-- changing it quietly. The hash cannot be reversed, so 1947 is restored.
DO $do$
DECLARE v text;
BEGIN
  SELECT value INTO v FROM public.app_security WHERE key = 'privacy_pin';
  IF v IS NOT NULL AND v LIKE '$2%' THEN
    UPDATE public.app_security
       SET value = '1947', updated_at = now()
     WHERE key = 'privacy_pin';
    INSERT INTO public.app_security_log (old_pin, new_pin, note)
    VALUES ('(was hashed, could not be read back)', '1947',
            'Reset to 1947 so the super-admin can read the PIN in Supabase.');
  END IF;
END
$do$;

-- Check a guess.
CREATE OR REPLACE FUNCTION public.verify_privacy_pin(p_pin text)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $fn$
DECLARE
  v_pin   text;
  v_fails int;
  v_until timestamptz;
BEGIN
  -- Office staff only. A broker login cannot even rattle the handle.
  IF NOT public.is_staff() THEN
    RAISE EXCEPTION 'Only office staff can unlock the screen.';
  END IF;

  SELECT value::int INTO v_fails
    FROM public.app_security WHERE key = 'pin_fail_count';
  SELECT value::timestamptz INTO v_until
    FROM public.app_security WHERE key = 'pin_blocked_until';

  IF v_until IS NOT NULL AND v_until > now() THEN
    RAISE EXCEPTION 'Too many wrong PINs. Try again in % seconds.',
      greatest(1, ceil(extract(epoch FROM (v_until - now())))::int);
  END IF;

  SELECT value INTO v_pin
    FROM public.app_security WHERE key = 'privacy_pin';
  IF v_pin IS NULL THEN
    -- No PIN set: do not lock the office out of its own screens.
    RETURN true;
  END IF;

  IF coalesce(p_pin, '') = v_pin THEN
    DELETE FROM public.app_security
     WHERE key IN ('pin_fail_count', 'pin_blocked_until');
    RETURN true;
  END IF;

  v_fails := coalesce(v_fails, 0) + 1;
  INSERT INTO public.app_security (key, value, updated_at)
  VALUES ('pin_fail_count', v_fails::text, now())
  ON CONFLICT (key) DO UPDATE
    SET value = excluded.value, updated_at = now();

  IF v_fails >= 5 THEN
    INSERT INTO public.app_security (key, value, updated_at)
    VALUES ('pin_blocked_until',
            (now() + interval '60 seconds')::text, now())
    ON CONFLICT (key) DO UPDATE
      SET value = excluded.value, updated_at = now();
    DELETE FROM public.app_security WHERE key = 'pin_fail_count';
  END IF;

  RETURN false;
END;
$fn$;

-- Change it from inside the app. Logs who, when, and from what to what.
CREATE OR REPLACE FUNCTION public.set_privacy_pin(p_current text, p_new text)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $fn$
DECLARE
  v_pin   text;
  v_name  text;
  v_email text;
BEGIN
  IF NOT public.is_staff() THEN
    RAISE EXCEPTION 'Only office staff can change the PIN.';
  END IF;
  IF p_new IS NULL OR p_new !~ '^[0-9]{4,8}$' THEN
    RAISE EXCEPTION 'The PIN must be 4 to 8 digits.';
  END IF;

  SELECT value INTO v_pin
    FROM public.app_security WHERE key = 'privacy_pin';
  -- Knowing the old PIN is required, so an unattended unlocked screen cannot
  -- be used to quietly set a new one and lock the office out.
  IF v_pin IS NOT NULL AND coalesce(p_current, '') <> v_pin THEN
    RAISE EXCEPTION 'The current PIN is wrong.';
  END IF;

  SELECT u.name, u.email INTO v_name, v_email
    FROM public.app_users u
   WHERE u.auth_user_id = auth.uid();

  INSERT INTO public.app_security (key, value, updated_at)
  VALUES ('privacy_pin', p_new, now())
  ON CONFLICT (key) DO UPDATE
    SET value = excluded.value, updated_at = now();

  INSERT INTO public.app_security_log
    (changed_by, changed_by_name, changed_by_email, old_pin, new_pin, note)
  VALUES (auth.uid(), v_name, v_email, v_pin, p_new,
          'Changed from the app (Change PIN).');

  DELETE FROM public.app_security
   WHERE key IN ('pin_fail_count', 'pin_blocked_until');
END;
$fn$;

-- Take it back without knowing the old one. For the owner, from the Supabase
-- SQL editor, when someone changed the PIN and is not around to tell you:
--
--     select public.reset_privacy_pin('1947');
--
-- EXECUTE is revoked from anon and authenticated below, so no employee can
-- call this through the API. The guard inside is a second lock on the same
-- door: it refuses any signed-in caller who is not the super-admin.
CREATE OR REPLACE FUNCTION public.reset_privacy_pin(p_new text)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $fn$
DECLARE
  v_pin   text;
  v_name  text;
  v_email text;
BEGIN
  -- coalesce, NOT a bare NOT.  is_super_admin() reads public.profiles, and four
  -- office logins (payout, alok, sanjeet, vikram) have no row there, so for them
  -- it returns NULL rather than false.  "NOT NULL" is NULL, an IF on NULL does
  -- not fire, and the guard would have waved exactly those logins through.
  IF auth.uid() IS NOT NULL
     AND coalesce(public.is_super_admin(), false) = false THEN
    RAISE EXCEPTION
      'Only the super-admin can reset the PIN without the old one.';
  END IF;
  IF p_new IS NULL OR p_new !~ '^[0-9]{4,8}$' THEN
    RAISE EXCEPTION 'The PIN must be 4 to 8 digits.';
  END IF;

  SELECT value INTO v_pin
    FROM public.app_security WHERE key = 'privacy_pin';
  SELECT u.name, u.email INTO v_name, v_email
    FROM public.app_users u
   WHERE u.auth_user_id = auth.uid();

  INSERT INTO public.app_security (key, value, updated_at)
  VALUES ('privacy_pin', p_new, now())
  ON CONFLICT (key) DO UPDATE
    SET value = excluded.value, updated_at = now();

  INSERT INTO public.app_security_log
    (changed_by, changed_by_name, changed_by_email, old_pin, new_pin, note)
  VALUES (auth.uid(), v_name, v_email, v_pin, p_new,
          'Reset by the super-admin without the old PIN.');

  DELETE FROM public.app_security
   WHERE key IN ('pin_fail_count', 'pin_blocked_until');

  RETURN 'PIN is now ' || p_new;
END;
$fn$;

-- One query for the owner: what the PIN is, when it last changed, and who
-- changed it. security_invoker = on so the view obeys the caller's own
-- permissions - if it were ever granted out by mistake, RLS on app_security
-- (on, with no policies) would still return nothing.
CREATE OR REPLACE VIEW public.privacy_pin_status
WITH (security_invoker = on) AS
SELECT s.value                                        AS current_pin,
       (s.updated_at AT TIME ZONE 'Asia/Kolkata')     AS last_changed_ist,
       l.changed_by_name                              AS last_changed_by,
       l.changed_by_email                             AS last_changed_by_email,
       l.old_pin                                      AS previous_pin,
       l.note                                         AS how,
       (SELECT count(*) FROM public.app_security_log) AS times_changed
  FROM public.app_security s
  LEFT JOIN LATERAL (
         SELECT * FROM public.app_security_log
          ORDER BY changed_at DESC, id DESC LIMIT 1
       ) l ON true
 WHERE s.key = 'privacy_pin';

REVOKE ALL ON public.privacy_pin_status FROM PUBLIC, anon, authenticated;

REVOKE EXECUTE ON FUNCTION public.verify_privacy_pin(text)
  FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.set_privacy_pin(text, text)
  FROM PUBLIC, anon;
REVOKE EXECUTE ON FUNCTION public.reset_privacy_pin(text)
  FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.verify_privacy_pin(text)
  TO authenticated;
GRANT EXECUTE ON FUNCTION public.set_privacy_pin(text, text)
  TO authenticated;

COMMIT;

