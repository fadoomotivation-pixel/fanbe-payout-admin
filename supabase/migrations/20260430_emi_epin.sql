    SELECT 1 FROM pg_trigger WHERE tgname = 'trg_epins_updated_at'
  ) THEN
    CREATE TRIGGER trg_epins_updated_at
      BEFORE UPDATE ON bp_epins
      FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
  END IF;
END $$;

