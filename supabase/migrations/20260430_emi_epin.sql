-- ─────────────────────────────────────────────────────────────
-- 3. E-PIN / REGISTRATION CODES
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS bp_epins (
  id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  code         TEXT NOT NULL UNIQUE,          -- 8-char alphanumeric, generated by app
  status       TEXT NOT NULL DEFAULT 'unused'
                 CHECK (status IN ('unused','used','expired','revoked')),
  expiry_date  DATE,                          -- NULL = no expiry
  used_by      UUID REFERENCES auth.users(id) ON DELETE SET NULL,
  used_at      TIMESTAMPTZ,
  notes        TEXT,                          -- e.g. batch name / camp
  created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE bp_epins IS 'Admin-generated one-time registration codes for broker/agent self-signup.';

CREATE INDEX IF NOT EXISTS idx_epins_code   ON bp_epins (code);
CREATE INDEX IF NOT EXISTS idx_epins_status ON bp_epins (status);

-- Auto-expire codes past their expiry_date
CREATE OR REPLACE FUNCTION fn_epin_auto_expire()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE bp_epins
     SET status = 'expired', updated_at = now()
   WHERE status = 'unused'
     AND expiry_date IS NOT NULL
     AND expiry_date < CURRENT_DATE;
END;
$$;

COMMENT ON FUNCTION fn_epin_auto_expire IS 'Call daily to expire unused codes past their expiry_date.';

DO $$ BEGIN
