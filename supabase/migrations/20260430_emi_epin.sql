-- ─────────────────────────────────────────────────────────────
-- 1. EMI PLANS
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS bp_emi_plans (
  id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  booking_id         UUID NOT NULL REFERENCES bp_bookings(id) ON DELETE CASCADE,
  frequency          TEXT NOT NULL CHECK (frequency IN ('monthly','quarterly','half_yearly','annually')),
  installment_count  INTEGER NOT NULL CHECK (installment_count > 0),
  installment_amount NUMERIC(14,2) NOT NULL,
  interest_rate      NUMERIC(5,2)  NOT NULL DEFAULT 0,  -- % per installment
  start_date         DATE NOT NULL,
  late_fee_per_day   NUMERIC(10,2) NOT NULL DEFAULT 0,
  bounce_charge      NUMERIC(10,2) NOT NULL DEFAULT 500,
  total_amount       NUMERIC(14,2) GENERATED ALWAYS AS (installment_count * installment_amount) STORED,
  notes              TEXT,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at         TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON TABLE bp_emi_plans IS 'One EMI plan per booking. Defines the instalment schedule parameters.';

-- ─────────────────────────────────────────────────────────────
-- 2. EMI SCHEDULE (auto-generated rows per plan)
-- ─────────────────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS bp_emi_schedule (
  id                     UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  plan_id                UUID NOT NULL REFERENCES bp_emi_plans(id) ON DELETE CASCADE,
  booking_id             UUID NOT NULL REFERENCES bp_bookings(id) ON DELETE CASCADE,
  installment_no         INTEGER NOT NULL,
  due_date               DATE NOT NULL,
  principal_amount       NUMERIC(14,2) NOT NULL,
  interest_amount        NUMERIC(10,2) NOT NULL DEFAULT 0,
  total_due              NUMERIC(14,2) NOT NULL,
  late_fee_per_day       NUMERIC(10,2) NOT NULL DEFAULT 0,
  bounce_charge          NUMERIC(10,2) NOT NULL DEFAULT 0,
  status                 TEXT NOT NULL DEFAULT 'pending'
                           CHECK (status IN ('pending','paid','overdue','waived','bounced')),
  paid_date              DATE,
  payment_reference      TEXT,
  days_late              INTEGER DEFAULT 0,
  late_fee_charged       NUMERIC(10,2) DEFAULT 0,
  bounce_charge_applied  NUMERIC(10,2) DEFAULT 0,
  created_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at             TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (plan_id, installment_no)
);

COMMENT ON TABLE bp_emi_schedule IS 'Individual instalment rows generated from bp_emi_plans.';

-- Auto-set status = overdue for unpaid instalments past due_date
CREATE OR REPLACE FUNCTION fn_emi_auto_overdue()
RETURNS void LANGUAGE plpgsql AS $$
BEGIN
  UPDATE bp_emi_schedule
     SET status = 'overdue', updated_at = now()
   WHERE status = 'pending'
     AND due_date < CURRENT_DATE;
END;
$$;

COMMENT ON FUNCTION fn_emi_auto_overdue IS 'Call daily via pg_cron or Supabase cron to mark overdue instalments.';

-- Trigger: keep updated_at fresh
CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  NEW.updated_at = now();
  RETURN NEW;
END;
$$;

